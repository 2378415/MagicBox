#!/usr/bin/env python3
"""Extract the MAKCU command table and opcode dispatch table from the official image.

Why a script and not hand-copied C: the 43 entries hold *string pointers* and the
dispatch table holds *code pointers*; both are absolute addresses inside the
flash image.  Re-emitting them from the image (with the original lengths,
argc/target fields and the handler entry addresses) keeps the rebuild honest and
re-runnable after any change to the name map.

Sources (LEFT image, see 官方固件命令协议.md §2/§4):
  0x42000DBC -> pointer to the command table base (0x3C03DF74)
  0x42000DC8 -> pointer to the opcode jump table (0x3C03DF08)

Outputs (into the rebuild project):
  components/makcu_proto/include/makcu_cmd.h
  components/makcu_proto/src/makcu_cmd_table.c
  components/makcu_proto/src/makcu_opcode_table.c

Usage:
  python tools/extract_tables.py                     # defaults to LEFT image
  python tools/extract_tables.py --image ... --out ...
"""
import argparse
import os
import struct
import sys
import io

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', errors='replace')

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.dirname(HERE)
OLD_REPO = os.path.dirname(PROJ)          # D:\JinPeng\MagicBox

SEGMENTS = [
    # vaddr,      len,      file offset
    (0x3C030020, 0x10B60, 0x010020),
    (0x3FC93D00, 0x3004,  0x020B88),
    (0x40374000, 0xC484,  0x023B94),
    (0x42000020, 0x2F040, 0x030020),
    (0x40380484, 0x3794,  0x05F068),
]
TABLE_PTR_ADDR = 0x42000DBC
JUMP_PTR_ADDR = 0x42000DC8
ENTRY_SIZE = 0x14
MAX_ENTRIES = 64
MAX_OPCODES = 32


def load_names():
    """entry address -> symbol name, taken from the reversed tree (source of truth)."""
    names = {}
    roots = [os.path.join(OLD_REPO, 'reversed', 'src', 'left'),
             os.path.join(OLD_REPO, 'reversed', 'manual', 'left')]
    for root in roots:
        for dirpath, _dirs, files in os.walk(root):
            for fn in files:
                if not fn.endswith('.c'):
                    continue
                entry, _, name = fn[:-2].partition('_')
                try:
                    names[int(entry, 16)] = name
                except ValueError:
                    continue
    return names


def is_code(addr):
    """True when the address points into IROM/IRAM (a real handler slot)."""
    inside = any(lo <= addr < lo + ln for lo, ln, _fo in SEGMENTS)
    return inside and (0x40370000 <= addr < 0x40400000 or 0x42000000 <= addr < 0x44000000)


class Image:
    def __init__(self, path):
        self.data = open(path, 'rb').read()

    def off(self, vaddr):
        for vaddr0, ln, fo in SEGMENTS:
            if vaddr0 <= vaddr < vaddr0 + ln:
                return fo + (vaddr - vaddr0)
        return None

    def u32(self, vaddr):
        o = self.off(vaddr)
        if o is None:
            return None
        return struct.unpack_from('<I', self.data, o)[0]

    def cstr(self, vaddr, limit=64):
        o = self.off(vaddr)
        if o is None:
            return None
        raw = self.data[o:o + limit].split(b'\0')[0]
        try:
            return raw.decode('ascii')
        except UnicodeDecodeError:
            return None


def read_cmd_table(img):
    base = img.u32(TABLE_PTR_ADDR)
    if base is None:
        raise SystemExit('command table pointer not in image')
    rows = []
    for i in range(MAX_ENTRIES):
        e = base + i * ENTRY_SIZE
        name_ptr = img.u32(e)
        if not name_ptr:
            break
        name = img.cstr(name_ptr)
        if name is None:
            break
        rows.append({
            'name': name,
            'len': img.u32(e + 4),
            'argc': img.u32(e + 8),
            'target': img.u32(e + 12),
            'opcode': img.u32(e + 16),
            'name_ptr': name_ptr,
        })
    return base, rows


def read_opcode_table(img):
    base = img.u32(JUMP_PTR_ADDR)
    if base is None:
        raise SystemExit('opcode table pointer not in image')
    slots = []
    for i in range(MAX_OPCODES):
        t = img.u32(base + i * 4)
        if t is None or not is_code(t):
            break                      # past the table: following words are data
        slots.append(t)
    return base, slots


C_HEADER = '''/* Generated by tools/extract_tables.py - do not edit by hand.
 *
 * Source image : {image}
 * Command table: {tbl:#010x}  ({n} entries x {esz:#x} bytes)
 * Names/lengths/argc/target/opcode are read straight out of flash.
 */
#ifndef MAKCU_CMD_H
#define MAKCU_CMD_H

#include <stdint.h>

#include <stddef.h>\n\n#define MAKCU_CMD_TEXT_PREFIX '.'      /* 0x2E: text frame marker */
#define MAKCU_PROMPT           ">>> "

typedef struct {{
    const char *name;      /* +0x00  literal, includes the trailing "(" or "()" */
    uint32_t    len;       /* +0x04  bytes compared by the prefix matcher      */
    uint32_t    argc;      /* +0x08  expected argument count (as used by handlers) */
    uint32_t    target;    /* +0x0C  1..5 button/axis id, 0 otherwise           */
    uint32_t    opcode;    /* +0x10  index into the handler table               */
}} makcu_cmd_t;

extern const makcu_cmd_t makcu_cmd_table[];
extern const unsigned    makcu_cmd_count;

/* Handler signature as recovered from cmd_dispatch (a2..a7, windowed ABI):
 *   buf = original line, len = its length, dev = device context,
 *   entry = matched table row, arg = buf + matched length, arglen = len - skip. */
typedef void (*makcu_handler_t)(const char *buf, int len, void *dev,
                                const makcu_cmd_t *entry,
                                const char *arg, int arglen);

extern const makcu_handler_t makcu_opcode_table[];
extern const unsigned        makcu_opcode_count;

/* prefix matcher, same semantics as cmd_lookup (0x4200EEC4) */
const makcu_cmd_t *makcu_lookup(const char *buf, int len, int *skip);

#endif /* MAKCU_CMD_H */
'''

C_TABLE = '''/* Generated by tools/extract_tables.py - do not edit by hand. */
#include "makcu_cmd.h"

const makcu_cmd_t makcu_cmd_table[] = {{
{rows}}};

const unsigned makcu_cmd_count = sizeof(makcu_cmd_table) / sizeof(makcu_cmd_table[0]);
'''

C_OPCODES = '''/* Generated by tools/extract_tables.py - do not edit by hand.
 * Slot addresses come from the jump table at {base:#010x}; names from the
 * reversed tree.  Slots with no handler start as NULL.
 */
#include "makcu_cmd.h"

{decls}
const makcu_handler_t makcu_opcode_table[] = {{
{rows}}};

const unsigned makcu_opcode_count = sizeof(makcu_opcode_table) / sizeof(makcu_opcode_table[0]);
'''


def load_implemented(out_dir):
    """Porting status per handler, from components/makcu_proto/handlers.def.

    Line format (tab or space separated, '#' starts a comment):
        0x0c  cmd_buttons  implemented
        0x19  cmd_silent   todo
    A handler that is still `todo` is emitted as NULL with its name kept in a
    comment, so the app links while the port is in progress and `app_main`
    reports the remaining count at boot.
    """
    path = os.path.join(out_dir, 'handlers.def')
    if not os.path.exists(path):
        return {}
    done = {}
    for line in open(path, encoding='utf-8'):
        line = line.split('#')[0].strip()
        if not line:
            continue
        parts = line.replace('\t', ' ').split()
        if len(parts) < 2:
            continue
        done[parts[1]] = (len(parts) > 2 and parts[2] == 'implemented')
    return done


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--image', default=os.path.join(OLD_REPO, '官方固件', 'V3.2_LEFT.bin'))
    ap.add_argument('--out', default=os.path.join(PROJ, 'components', 'makcu_proto'))
    a = ap.parse_args()

    img = Image(a.image)
    tbl, cmds = read_cmd_table(img)
    jmp, slots = read_opcode_table(img)
    names = load_names()
    implemented = load_implemented(a.out)

    os.makedirs(os.path.join(a.out, 'include'), exist_ok=True)
    os.makedirs(os.path.join(a.out, 'src'), exist_ok=True)

    rel_image = os.path.relpath(a.image, PROJ).replace('\\', '/')
    with open(os.path.join(a.out, 'include', 'makcu_cmd.h'), 'w', encoding='utf-8') as fh:
        fh.write(C_HEADER.format(image=rel_image, tbl=tbl, n=len(cmds), esz=ENTRY_SIZE))

    rows = []
    for c in cmds:
        rows.append('    {{ "{name}", {len}, {argc}, {target}, {opcode} }}, /* {name_ptr:#x} */\n'
                    .format(name=c['name'].replace('\\', '\\\\').replace('"', '\\"'),
                            len=c['len'], argc=c['argc'], target=c['target'],
                            opcode=c['opcode'], name_ptr=c['name_ptr']))
    with open(os.path.join(a.out, 'src', 'makcu_cmd_table.c'), 'w', encoding='utf-8') as fh:
        fh.write(C_TABLE.format(rows=''.join(rows)))

    decls, orows, missing = [], [], []
    for i, addr in enumerate(slots):
        if addr is None:
            orows.append('    NULL,\n')
            continue
        name = names.get(addr)
        if name and implemented.get(name, False):
            decls.append('void {name}(const char *buf, int len, void *dev,\n'
                         '        const makcu_cmd_t *entry, const char *arg, int arglen);\n'
                         .format(name=name))
            orows.append('    {name}, /* {i:#04x} <- {addr:#010x} */\n'.format(name=name, i=i, addr=addr))
        elif name:
            orows.append('    NULL, /* {i:#04x} {name} TODO ({addr:#010x}) */\n'
                         .format(i=i, name=name, addr=addr))
        else:
            decls.append('/* TODO opcode {i:#04x}: handler at {addr:#010x} not reconstructed */\n'
                         .format(i=i, addr=addr))
            missing.append((i, addr))
            orows.append('    NULL, /* {i:#04x} TODO {addr:#010x} */\n'.format(i=i, addr=addr))
    with open(os.path.join(a.out, 'src', 'makcu_opcode_table.c'), 'w', encoding='utf-8') as fh:
        fh.write(C_OPCODES.format(base=jmp, decls=''.join(decls), rows=''.join(orows)))

    print(f'command table @ {tbl:#010x}: {len(cmds)} entries')
    for c in cmds:
        print(f"  {c['name']:<24} len={c['len']:<2} argc={c['argc']} "
              f"target={c['target']} opcode={c['opcode']:#04x}")
    print(f'opcode table @ {jmp:#010x}: {len(slots)} slots, '
          f'{sum(1 for s in slots if s)} non-null, {len(missing)} without a handler name')
    for i, addr in missing:
        print(f'  TODO opcode {i:#04x} -> {addr:#010x}')


if __name__ == '__main__':
    main()
